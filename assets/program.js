function skillScores(answers){
  var out={contract:[],sources:[],apply:[],spot:[],exam:[]};
  (answers||[]).forEach(function(a){if(!out[a.skill])out[a.skill]=[];out[a.skill].push(a.correct?1:0);});
  Object.keys(out).forEach(function(k){var a=out[k];out[k]=a.length?Math.round(a.reduce(function(x,y){return x+y;},0)/a.length*100):null;});
  return out;
}
function achievementLabel(status){
  return status==="mastered"?"مكتمل بإتقان":status==="completed"?"مكتمل بنجاح":status==="completed_with_support"?"مكتمل بعد جلسة دعم":"يحتاج جلسة تثبيت";
}
function addAchievement(week,status){
  var id="week-"+week+"-"+status;if(!state.course.achievements.some(function(a){return a.id===id;}))state.course.achievements.push({id:id,week:week,status:status,ts:Date.now()});
}
function finishAssessment(){
  var a=state.assessmentAnswers,c=a.filter(function(x){return x.correct;}).length,p=Math.round(c/(a.length||1)*100),week=sessionMeta(state.course.session).week;
  var status=p>=80?"mastered":p>=60?"completed":"repair";
  var r={week:week,score:p,status:status,skillScores:skillScores(a),ts:Date.now()};
  state.course.lastAssessment={session:state.course.session,score:p,week:week,status:status,ts:Date.now()};
  state.course.weekResults[week]=r;
  state.course.history.push({session:state.course.session,type:"assessment",score:p,answers:a,week:week,ts:Date.now()});
  pushUnique(state.course.completed,state.course.session);
  if(status==="repair"){
    state.course.repairRequired=true;state.course.repairWeek=week;
  }else{
    state.course.repairRequired=false;state.course.repairWeek=null;addAchievement(week,status);
    if(week===6){
      state.course.completedProgram=true;
      state.course.completedAt=Date.now();
      state.course.session=30;
      addAchievement(6,"program-complete");
    }else{
      state.course.session=Math.min(30,state.course.session+1);
    }
  }
  save();state.view=(week===6&&status!=="repair")?"completion":"achievement";render();
}
function achievementSkill(name,v,iconName){
  var label=v==null?"لم يُقَس":v>=80?"قوي":v>=60?"جيد":v>=40?"يحتاج تركيز":"يحتاج تثبيت";
  var pct=v==null?0:Math.max(0,Math.min(100,Math.round(v)));
  return '<div class="stageMetricCard"><div class="stageMetricTop"><span class="stageMetricIcon">'+ico(iconName)+'</span><b>'+name+'</b></div><div class="stageMetricValue">'+(v==null?"—":pct+"%")+'</div><div class="stageMetricBar"><i style="width:'+(v==null?4:pct)+'%"></i></div><small>'+label+'</small></div>';
}
function averageScores(values){
  var a=values.filter(function(v){return v!=null&&!isNaN(Number(v));}).map(Number);
  if(!a.length)return null;
  return Math.round(a.reduce(function(x,y){return x+y;},0)/a.length);
}
function stageAdvice(knowledge,analysis,exam){
  var items=[["المعرفة القانونية",knowledge],["التحليل والتطبيق",analysis],["الإجابة الامتحانية",exam]].filter(function(x){return x[1]!=null;}).sort(function(a,b){return a[1]-b[1];});
  if(!items.length)return "ابدأ جلسة التثبيت القصيرة ثم أعد القياس.";
  if(items[0][0]==="المعرفة القانونية")return "راجع عناصر القاعدة ومصدر الالتزام في صورة نقاط قصيرة قبل إعادة القياس.";
  if(items[0][0]==="التحليل والتطبيق")return "ركز على الواقعة الحاسمة ثم اربطها بالقاعدة بدل إعادة حفظ النص.";
  return "استخدم ترتيبًا ثابتًا للإجابة: المسألة ثم القاعدة ثم التطبيق ثم النتيجة.";
}
