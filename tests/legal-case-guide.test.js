const assert=require("node:assert/strict");
const guide=require("../assets/legal-case-guide.js");
const ar="الواقعة: وجد سبب حق للحمل لا يحتاج إلى قبول، ثم تمت ولادته حيًا. ما أثر الولادة على الحق المقصود؟\nالمسألة: اكتب السؤال القانوني المطلوب حسمه في الواقعة، بجملة واحدة.\nالقاعدة: اذكر القاعدة أو الشرط القانوني الذي ستعتمد عليه؛ لا يلزم رقم المادة إلا إذا طُلب.\nالتطبيق: اربط الوقائع بالقاعدة، ووضّح لماذا تتحقق شروطها أو لا تتحقق.\nالنتيجة: أجب عن سؤال الواقعة بوضوح، مع سبب مختصر. اكتب كل جزء تحت عنوانه.";
const en="Facts: The cause of a prenatal right requiring no acceptance existed, and the child was later born alive. What follows?\nIssue: state the legal question raised by the facts in one sentence.\nRule: identify the relevant legal rule or condition; an article number is not required unless requested.\nApplication: connect the facts to the rule and explain which conditions are or are not met.\nConclusion: answer the question clearly with a brief reason. Use a heading for each section.";
const parsedAr=guide.parse(ar,"ar"),parsedEn=guide.parse(en,"en");
assert.ok(parsedAr&&parsedEn,"both languages must parse one case with four legal skills");
assert.equal(parsedAr.facts,"وجد سبب حق للحمل لا يحتاج إلى قبول، ثم تمت ولادته حيًا.");
assert.equal(parsedAr.question,"ما أثر الولادة على الحق المقصود؟");
assert.equal(parsedEn.question,"What follows?");
assert.deepEqual(Object.keys(parsedAr.sections),["facts","issue","rule","application","conclusion"]);
assert.equal(guide.parse("اشرح كيف تبدأ الشخصية القانونية.", "ar"),null,"other skill prompts remain plain, without forced IRAC");
assert.equal(guide.parse("الواقعة: ليس هنا تعليمات أخرى", "ar"),null);
const answer=guide.compose(["ما أثر ولادته حيًا على الحق؟","يثبت الحق للحمل بشرط الولادة حياً.","تحققت الولادة الحية.","ثبت الحق لتحقق شرطه."],"ar");
assert.ok(answer.includes("المسألة: "));
assert.ok(answer.includes("القاعدة: "));
assert.ok(answer.includes("التطبيق: "));
assert.ok(answer.includes("النتيجة: "));
assert.ok(answer.length<4000);
assert.equal(guide.compose(["","","","النتيجة القانونية"],"ar"),"النتيجة: النتيجة القانونية",
 "never award heading-only structure points for unanswered steps");
assert.equal(guide.compose(["Issue?","Rule","Facts","Result"],"en").split("\n")[0],"Issue: Issue?");
const fs=require("node:fs");
const student=fs.readFileSync("assets/student-path.js","utf8"),page=fs.readFileSync("student-path.html","utf8"),builder=fs.readFileSync("scripts/build-public.js","utf8");
assert.match(student,/next\.dimension==="exam_execution"/);
assert.match(student,/guide\.mount\(/);
assert.match(student,/studentLifecycleRpc\("trainingSubmit"/);
assert.match(page,/assets\/legal-case-guide\.js/);
assert.match(page,/assets\/legal-case-guide\.css/);
assert.match(builder,/"legal-case-guide\.js"/);
assert.match(builder,/"legal-case-guide\.css"/);
console.log("PASS: question extraction, guided learning sections, rubric format, fallback and published assets");
